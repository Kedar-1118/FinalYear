"""Automated HTML Performance Report & Visual Dashboard Generator for MABSplit."""

import os
import json
import time
from typing import Dict, Any, List, Optional
import numpy as np


class MABReportGenerator:
    """Generates standalone visual HTML benchmark reports and executive performance dashboards."""

    def __init__(self, title: str = "MABSplit Benchmark & Evaluation Report"):
        self.title = title
        self.metrics_history: List[Dict[str, Any]] = []

    def add_benchmark_run(
        self,
        model_name: str,
        n_samples: int,
        n_features: int,
        training_time_sec: float,
        accuracy: float,
        samples_evaluated: int,
        memory_mb: float = 0.0
    ):
        """Records a single benchmark configuration result."""
        self.metrics_history.append({
            "model_name": model_name,
            "n_samples": n_samples,
            "n_features": n_features,
            "training_time_sec": round(float(training_time_sec), 4),
            "accuracy": round(float(accuracy) * 100.0, 2),
            "samples_evaluated": int(samples_evaluated),
            "memory_mb": round(float(memory_mb), 2)
        })

    def generate_html_report(self, output_path: str = "experiments/plots/report.html") -> str:
        """Renders an interactive HTML document with styled metrics tables and CSS cards."""
        rows_html = ""
        for item in self.metrics_history:
            rows_html += f"""
            <tr>
                <td><strong>{item['model_name']}</strong></td>
                <td>{item['n_samples']:,}</td>
                <td>{item['n_features']}</td>
                <td><span class="badge time">{item['training_time_sec']} s</span></td>
                <td><span class="badge acc">{item['accuracy']}%</span></td>
                <td>{item['samples_evaluated']:,}</td>
                <td>{item['memory_mb']} MB</td>
            </tr>
            """

        html_content = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{self.title}</title>
    <style>
        body {{
            font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif;
            background-color: #0f172a;
            color: #f8fafc;
            margin: 0;
            padding: 40px;
        }}
        .container {{
            max-width: 1100px;
            margin: 0 auto;
            background: #1e293b;
            padding: 32px;
            border-radius: 12px;
            box-shadow: 0 10px 25px rgba(0,0,0,0.5);
        }}
        h1 {{
            color: #38bdf8;
            border-bottom: 2px solid #334155;
            padding-bottom: 12px;
            margin-top: 0;
        }}
        .subtitle {{
            color: #94a3b8;
            font-size: 1.1em;
            margin-bottom: 24px;
        }}
        table {{
            width: 100%;
            border-collapse: collapse;
            margin-top: 20px;
        }}
        th, td {{
            padding: 12px 16px;
            text-align: left;
            border-bottom: 1px solid #334155;
        }}
        th {{
            background-color: #0f172a;
            color: #38bdf8;
            font-weight: 600;
        }}
        tr:hover {{
            background-color: #334155;
        }}
        .badge {{
            padding: 4px 8px;
            border-radius: 4px;
            font-weight: bold;
            font-size: 0.9em;
        }}
        .badge.time {{
            background: #0284c7;
            color: #ffffff;
        }}
        .badge.acc {{
            background: #16a34a;
            color: #ffffff;
        }}
        .footer {{
            margin-top: 32px;
            font-size: 0.85em;
            color: #64748b;
            text-align: center;
        }}
    </style>
</head>
<body>
    <div class="container">
        <h1>📊 {self.title}</h1>
        <div class="subtitle">Generated by MABSplit Visual Report Generator | Active Arm Elimination Benchmarks</div>
        <table>
            <thead>
                <tr>
                    <th>Model Variant</th>
                    <th>Samples (N)</th>
                    <th>Features (D)</th>
                    <th>Training Time</th>
                    <th>Accuracy</th>
                    <th>Sample Evaluations</th>
                    <th>Peak Memory</th>
                </tr>
            </thead>
            <tbody>
                {rows_html if rows_html else '<tr><td colspan="7">No benchmark runs recorded.</td></tr>'}
            </tbody>
        </table>
        <div class="footer">MABSplit: Accelerated Decision Tree & Random Forest Training Framework</div>
    </div>
</body>
</html>
"""
        abs_path = os.path.abspath(output_path)
        os.makedirs(os.path.dirname(abs_path), exist_ok=True)
        with open(abs_path, 'w', encoding='utf-8') as f:
            f.write(html_content)
        return abs_path


if __name__ == '__main__':
    generator = MABReportGenerator()
    generator.add_benchmark_run("Sklearn Exact DecisionTree", 50000, 25, 2.56, 0.902, 500000, 45.2)
    generator.add_benchmark_run("MABDecisionTree (Ours)", 50000, 25, 1.32, 0.905, 383374, 12.8)
    out_file = generator.generate_html_report()
    print(f"Generated visual report at: {out_file}")
